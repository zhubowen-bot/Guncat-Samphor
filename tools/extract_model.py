"""Extract the embedded 2M model from the original HTML, truncate the unused
embedding rows, and quantize 2-D weight matrices to per-row int8.

Output: src/weights.js  (ES module, browser + Node compatible)
"""
import base64
import glob
import json
import re
import struct

import numpy as np

# The enhanced build also lives in the repo; only the original file contains
# the `const weights_b64` block we extract from.
SRC = next(
    p for p in glob.glob("*.html")
    if "增强版" not in p and "const weights_b64" in open(p, encoding="utf-8", errors="replace").read(400000)
)
OUT = "src/weights.js"
VOCAB_OUT = "src/vocab.js"

html = open(SRC, encoding="utf-8", errors="replace").read()
start = html.index("const weights_b64")
end = html.index("const config", start)
blk = html[start:end]
pat = re.compile(
    r'"([\w.]+)"\s*:\s*\{\s*"size"\s*:\s*\[([^\]]*)\]\s*,\s*"data"\s*:\s*"([^"]*)"',
    re.S,
)
weights = {}
for m in pat.finditer(blk):
    name = m.group(1)
    size = [int(x) for x in m.group(2).replace("\n", " ").split(",") if x.strip()]
    raw = base64.b64decode(m.group(3))
    arr = np.frombuffer(raw, dtype="<f4").copy()
    if len(size) == 2:
        arr = arr.reshape(size)
    weights[name] = arr

# Vocab
vm = re.search(r"const vocab = \[(.*?)\]", html, re.S)
vocab = [json.loads(x) for x in re.findall(r'"(?:[^"\\]|\\.)*"', vm.group(1))]
assert len(vocab) == 609, len(vocab)
assert weights["embed.weight"].shape[0] == 4096

# Only the first 609 embedding rows are mapped by the vocabulary.  Rows above
# that were sampled by the original app and produced `undefined` characters.
V = len(vocab)
embed = weights["embed.weight"][:V]
out = {}
total_q = 0
total_f32 = 0

for name, arr in weights.items():
    if name == "embed.weight":
        arr = embed
    if arr.ndim == 2:
        rows, cols = arr.shape
        qrows = []
        scales = []
        for r in range(rows):
            row = arr[r].astype(np.float64)
            max_abs = float(np.max(np.abs(row)))
            scale = max_abs / 127.0 if max_abs > 0 else 1.0
            q = np.clip(np.rint(row / scale), -127, 127).astype(np.int8)
            qrows.append(q)
            scales.append(scale)
        data = np.stack(qrows, axis=0).astype(np.int8).tobytes()
        out[name] = {
            "size": [rows, cols],
            "dtype": "int8",
            "data": base64.b64encode(data).decode("ascii"),
            "scales": scales,
        }
        total_q += rows * cols
    else:
        data = arr.astype("<f4").tobytes()
        out[name] = {
            "size": [int(arr.shape[0])],
            "dtype": "f32",
            "data": base64.b64encode(data).decode("ascii"),
        }
        total_f32 += int(arr.shape[0])

config = {
    "vocab_size": V,
    "hidden_size": 128,
    "num_layers": 6,
    "num_heads": 4,
    "intermediate_size": 512,
    "norm_eps": 1e-5,
    "max_seq_len": 256,
}

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by tools/extract_model.py. Do not edit by hand.\n")
    f.write("// 2M-parameter char-level Llama-style model, int8 per-row quantized.\n")
    f.write("export const MODEL_CONFIG = ")
    f.write(json.dumps(config, ensure_ascii=False, indent=2))
    f.write(";\n\n")
    f.write("export const MODEL_WEIGHTS = ")
    f.write(json.dumps(out, ensure_ascii=False, separators=(",", ":")))
    f.write(";\n")

with open(VOCAB_OUT, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by tools/extract_model.py. Do not edit by hand.\n")
    f.write("export const VOCAB = ")
    f.write(json.dumps(vocab, ensure_ascii=False, separators=(",", ":")))
    f.write(";\n")

import os
print("source", SRC)
print("vocab", V)
print("int8 params", total_q, "f32 params", total_f32)
print("weights.js MB", os.path.getsize(OUT) / 1e6)
print("vocab.js MB", os.path.getsize(VOCAB_OUT) / 1e6)
